"use client";
import { useCallback, useState } from "react";
import DynamicWizard from "../../components/DynamicWizard";
import { Button } from "../../components/ui";
import { initialValues } from "../form/formSchema";

const API_URL = process.env.NEXT_PUBLIC_API_URL || "http://localhost:4000";

// A component that crashes on purpose, to prove the page survives it.
const BROKEN_CODE = `function Wizard() { throw new Error("Simulated broken component"); }`;

// Pretend the user already typed these before getting stuck on the PAN field.
const DEMO_VALUES = { ...initialValues(), fullName: "Sahana PM", email: "sahana@example.com", pan: "ABCDE12" };
const DEMO_FRICTION = { fieldId: "pan", errors: 4, hesitations: 3, dwellSeconds: 21 };

export default function RendererTestPage() {
  const [code, setCode] = useState("");
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState("Choose an option above to load a wizard.");
  const [violations, setViolations] = useState([]);
  const [submitted, setSubmitted] = useState(null);

  const handleError = useCallback((err) => setMessage(`Render problem caught safely: ${err.message}`), []);

  const run = async (label, task) => {
    setBusy(true);
    setMessage(label);
    setViolations([]);
    setSubmitted(null);
    try {
      await task();
    } catch (err) {
      setMessage(`Request failed: ${err.message}. Is the backend running on ${API_URL}?`);
    } finally {
      setBusy(false);
    }
  };

  const loadSaved = () =>
    run("Loading a saved wizard...", async () => {
      const res = await fetch(`${API_URL}/api/sample-wizard`);
      const data = await res.json();
      if (!data.ok) return setMessage(data.error);
      setCode(data.js);
      setMessage(`Loaded ${data.source} (checked by the security validator).`);
    });

  const generate = () =>
    run("Asking the AI for a new wizard (about 10 seconds)...", async () => {
      const typed = Object.fromEntries(Object.entries(DEMO_VALUES).filter(([, v]) => v !== "" && v !== false));
      const res = await fetch(`${API_URL}/api/generate`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ values: typed, friction: DEMO_FRICTION }),
      });
      const data = await res.json();
      if (!data.ok) {
        setViolations(data.violations || []);
        return setMessage(data.error);
      }
      setCode(data.js);
      setMessage(`Generated by ${data.provider} (${data.model}) in ${(data.ms / 1000).toFixed(1)} s.`);
    });

  const loadBroken = () => {
    setSubmitted(null);
    setViolations([]);
    setMessage("Loaded a component that crashes on purpose.");
    setCode(BROKEN_CODE);
  };

  return (
    <main className="mx-auto max-w-3xl space-y-6 p-6">
      <div>
        <h1 className="text-2xl font-bold">Dynamic renderer test</h1>
        <p className="text-sm text-gray-600">
          The backend sends compiled code. The browser turns it into a live component without a page refresh.
        </p>
      </div>

      <div className="flex flex-wrap gap-3">
        <Button onClick={loadSaved} disabled={busy}>Load saved wizard (no AI)</Button>
        <Button variant="secondary" onClick={generate} disabled={busy}>Generate with AI</Button>
        <Button variant="danger" onClick={loadBroken} disabled={busy}>Load a broken component</Button>
        <Button variant="ghost" onClick={() => { setCode(""); setSubmitted(null); setMessage("Cleared."); }} disabled={busy}>
          Clear
        </Button>
      </div>

      <p className="rounded-lg bg-gray-100 p-3 text-sm text-gray-700">{message}</p>

      {violations.length > 0 && (
        <ul className="list-disc space-y-1 rounded-lg border border-red-200 bg-red-50 p-4 pl-8 text-sm text-red-800">
          {violations.map((v, i) => (
            <li key={i}>[{v.rule}] {v.message}{v.line ? ` (line ${v.line})` : ""}</li>
          ))}
        </ul>
      )}

      <section className="rounded-xl border border-gray-200 p-4">
        <DynamicWizard
          code={code}
          initialValues={DEMO_VALUES}
          onSubmit={(values) => setSubmitted(values)}
          onError={handleError}
        />
      </section>

      {submitted && (
        <section className="rounded-xl border border-green-300 bg-green-50 p-4">
          <p className="font-semibold text-green-800">Wizard submitted these values:</p>
          <pre className="mt-2 overflow-x-auto text-xs text-green-900">{JSON.stringify(submitted, null, 2)}</pre>
        </section>
      )}
    </main>
  );
}